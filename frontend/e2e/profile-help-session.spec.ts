import { test, expect } from "@playwright/test";
import { readFileSync } from "node:fs";
import { MANAGER_USER_FILE } from "./global-setup";
import { api, login, revealWorkspaceHeader } from "./helpers";
import { buildPath } from "../src/i18n/routing";
import tr from "../src/i18n/messages/tr.json";
import en from "../src/i18n/messages/en.json";
import de from "../src/i18n/messages/de.json";

test("profile help preserves the page, cookies and real session, including public navigation and refresh", async ({ page, context }) => {
  await page.emulateMedia({ reducedMotion: "reduce" });
  const user = JSON.parse(readFileSync(MANAGER_USER_FILE, "utf8"));
  await login(page, user.email, user.password);
  await page.goto("/account");
  await expect(page.locator("#main-content")).toBeVisible();
  const originalUrl = page.url();
  const authCookies = async () => (await context.cookies()).filter(c => ["PDA_ACCESS", "PDA_REFRESH", "PDA_SESSION"].includes(c.name)).sort((a, b) => a.name.localeCompare(b.name));
  const before = await authCookies();
  expect(before).toHaveLength(3);
  const logoutRequests: string[] = [];
  page.on("request", request => { if (request.url().endsWith("/auth/logout")) logoutRequests.push(request.url()); });
  const openMenu = async () => {
    await revealWorkspaceHeader(page);
    await page.getByRole("button", { name: tr.workspace.account, exact: false }).click();
  };
  await openMenu();
  await page.getByRole("menuitem", { name: tr.siteFooter.faq }).click();
  const faq = page.locator("[data-workspace-faq]");
  await expect(faq).toBeVisible();
  await faq.locator("summary").first().click();
  await expect(faq.locator("details[open] p")).toBeVisible();
  await expect(page).toHaveURL(new RegExp(buildPath("/account/faq", {}, "tr") + "\\?"));
  await page.reload();
  await expect(faq).toBeVisible();
  await page.screenshot({ path: "test-results/profile-faq-desktop.png" });
  await faq.getByRole("button", { name: tr.workspace.history.back, exact: true }).click();
  await expect(page).toHaveURL(originalUrl);
  await expect(faq).toHaveCount(0);
  await openMenu();
  await page.getByRole("menuitem", { name: tr.siteFooter.manageCookies }).click();
  const preferences = page.locator("[data-cookie-dialog]");
  await expect(preferences).toBeVisible();
  await preferences.getByRole("button", { name: tr.consent.dialog.acceptAll }).click();
  await openMenu();
  await page.getByRole("menuitem", { name: tr.siteFooter.manageCookies }).click();
  await expect(preferences.getByRole("checkbox", { name: tr.consent.dialog.analytics.title })).toBeChecked();
  await preferences.getByRole("checkbox", { name: tr.consent.dialog.analytics.title }).uncheck();
  await preferences.getByRole("button", { name: tr.consent.dialog.save, exact: true }).click();
  expect(page.url()).toBe(originalUrl);
  expect(await authCookies()).toEqual(before);
  expect((await api(page, "GET", "/auth/me")).status).toBe(200);
  await page.reload();
  await expect(page.locator("#main-content")).toBeVisible();
  await revealWorkspaceHeader(page);
  await page.getByRole("button", { name: tr.common.theme.dark, exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await openMenu();
  await page.getByRole("menuitem", { name: tr.siteFooter.faq }).click();
  await expect(faq).toBeVisible();
  await page.screenshot({ path: "test-results/profile-faq-mobile.png" });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await faq.getByRole("button", { name: tr.workspace.history.back, exact: true }).click();
  await expect(page).toHaveURL(originalUrl);
  await openMenu();
  await page.getByRole("menuitem", { name: tr.siteFooter.contact, exact: true }).click();
  await expect(page).toHaveURL(new RegExp(buildPath("/account/contact", {}, "tr") + "\\?"));
  await expect(page.locator(".app-shell [data-contact-page]")).toBeVisible();
  expect(await authCookies()).toEqual(before);
  await page.reload();
  await expect(page.locator(".app-shell [data-contact-page]")).toBeVisible();
  await page.screenshot({ path: "test-results/profile-contact-mobile.png" });
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.screenshot({ path: "test-results/profile-contact-desktop.png" });
  expect((await api(page, "GET", "/auth/me")).status).toBe(200);
  await page.locator("[data-contact-page]").getByRole("button", { name: tr.workspace.history.back, exact: true }).click();
  await expect(page).toHaveURL(originalUrl);
  await expect(page.locator("#main-content")).toBeVisible();
  await page.goto("/faq");
  await expect(page).toHaveURL(new RegExp(buildPath("/account/faq", {}, "tr") + "$"));
  await expect(page.locator(".app-shell [data-workspace-faq]")).toBeVisible();
  await expect(page.locator("#public-main")).toHaveCount(0);
  await expect(page.locator(`a[href="${buildPath("/login", {}, "tr")}"]`)).toHaveCount(0);
  await page.goto("/dashboard");
  await expect(page.locator("#main-content")).toBeVisible();
  expect(logoutRequests).toEqual([]);
  expect((await api(page, "GET", "/auth/me")).status).toBe(200);
  // TEST-ONLY: expire only the access cookie to exercise the actual refresh rotation.
  const access = (await authCookies()).find(cookie => cookie.name === "PDA_ACCESS")!;
  await context.addCookies([{ ...access, expires: 1 }]);
  await page.goto("/faq");
  await expect(page.locator(".app-shell [data-workspace-faq]")).toBeVisible();
  await page.goto("/dashboard");
  await expect(page.locator("#main-content")).toBeVisible();
  expect((await api(page, "GET", "/auth/me")).status).toBe(200);
  expect(await authCookies()).toHaveLength(3);
  await page.goto("/");
  await expect(page.locator("#main-content")).toBeVisible();
  expect(logoutRequests).toEqual([]);
  await openMenu();
  await page.getByRole("menuitem", { name: tr.app.nav.logout }).click();
  await expect(page).toHaveURL(new RegExp(buildPath("/login", {}, "tr") + "$"));
  expect(await authCookies()).toHaveLength(0);
  expect(logoutRequests).toHaveLength(1);
});

test("workspace FAQ shares localized content and fits narrow screens", async ({ page }) => {
  await page.emulateMedia({ reducedMotion: "reduce" });
  const user = JSON.parse(readFileSync(MANAGER_USER_FILE, "utf8"));
  await login(page, user.email, user.password);
  await page.setViewportSize({ width: 320, height: 700 });
  for (const [locale, messages] of [["tr", tr], ["en", en], ["de", de]] as const) {
    await page.goto(buildPath("/account", {}, locale));
    await expect(page.locator("#main-content")).toBeVisible();
    await page.getByRole("button", { name: messages.workspace.account, exact: false }).click();
    await page.getByRole("menuitem", { name: messages.siteFooter.faq }).click();
    const faq = page.locator("[data-workspace-faq]");
    await expect(faq).toBeVisible();
    await expect(faq.locator("summary").first()).toHaveText(messages.publicPages.faq.groups[0].questions[0].question);
    await faq.locator("summary").first().focus();
    await page.keyboard.press("Enter");
    await expect(faq.locator("details[open] p")).toHaveText(messages.publicPages.faq.groups[0].questions[0].answer);
    const box = (await faq.boundingBox())!;
    expect(box.x).toBeGreaterThanOrEqual(0);
    expect(box.x + box.width).toBeLessThanOrEqual(320);
    await faq.getByRole("button", { name: messages.workspace.history.back, exact: true }).click();
    await expect(page).toHaveURL(new RegExp(buildPath("/account", {}, locale) + "$"));
    await page.goto(buildPath("/faq", {}, locale));
    await expect(page).toHaveURL(new RegExp(buildPath("/account/faq", {}, locale) + "$"));
    await expect(page.locator(".app-shell [data-workspace-faq]")).toBeVisible();
    await expect(page.locator("#public-main")).toHaveCount(0);
    await page.goto(buildPath("/contact", {}, locale));
    await expect(page).toHaveURL(new RegExp(buildPath("/account/contact", {}, locale) + "$"));
    await expect(page.locator(".app-shell [data-contact-page]")).toBeVisible();
    await expect(page.locator("[data-contact-page] h1")).toHaveText(messages.contact.title);
    await expect(page.locator("[data-contact-page]")).toContainText(messages.contact.workspaceDescription);
    await expect(page.locator("#public-main")).toHaveCount(0);
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  }
});

test("anonymous FAQ and cookie preferences remain available", async ({ page }) => {
  await page.goto("/faq");
  await expect(page.locator("header").getByRole("link", { name: "Giriş yap", exact: true })).toBeVisible();
  await page.locator("article summary").first().click();
  await expect(page.locator("article details[open] p")).toBeVisible();
  await page.locator("footer").getByRole("button", { name: tr.siteFooter.manageCookies }).click();
  await expect(page.locator("[data-cookie-dialog]")).toBeVisible();
  await page.locator("[data-cookie-dialog]").getByRole("button", { name: tr.consent.dialog.rejectAll }).click();
  await expect(page.locator("[data-cookie-dialog]")).toHaveCount(0);
  await page.goto("/account/faq");
  await expect(page).toHaveURL(/\/tr\/giris\?next=/);
  await expect(page.locator("[data-workspace-faq]")).toHaveCount(0);
  await page.goto("/contact");
  await expect(page.locator("#public-main [data-contact-page]")).toBeVisible();
  await expect(page.locator("header").getByRole("link", { name: "Giriş yap", exact: true })).toBeVisible();
  await page.goto("/account/contact");
  await expect(page).toHaveURL(/\/tr\/giris\?next=/);
});
